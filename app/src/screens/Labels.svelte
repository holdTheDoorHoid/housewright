<script lang="ts">
  // A printable sheet of QR stickers (D-30): one per thing, with its short
  // code and name. The sheet is a PDF so it prints the same from a phone or
  // a computer. Label grids vary; a test print on plain paper is the check.
  import { call, type Sticker, type SheetLayout } from '../lib/api';
  import { toast } from '../lib/state.svelte';
  import { errorText } from '../lib/actions';
  import { openFile } from '../lib/files';

  let stickers = $state<Sticker[]>([]);
  let presets = $state<{ key: string; label: string; layout: SheetLayout }[]>([]);
  let chosen = $state<string[]>([]);
  let preset = $state('letter-30');
  let custom = $state<SheetLayout | null>(null);
  let outline = $state(false);
  let busy = $state(false);
  let error = $state<string | null>(null);

  $effect(() => {
    call('label_sheet', {})
      .then((r) => {
        stickers = r.stickers;
        presets = r.presets;
        chosen = r.stickers.map((s) => s.item_id);
      })
      .catch((e) => (error = errorText(e)));
  });

  const layout = $derived<SheetLayout | null>(
    preset === 'custom' ? custom : (presets.find((p) => p.key === preset)?.layout ?? null),
  );

  function toggle(id: string) {
    chosen = chosen.includes(id) ? chosen.filter((x) => x !== id) : [...chosen, id];
  }

  function useCustom() {
    custom = { ...(presets.find((p) => p.key === 'letter-30')?.layout ?? presets[0].layout) };
  }

  async function make() {
    if (!layout) return;
    busy = true;
    try {
      await openFile(
        'label_sheet_pdf',
        { item_ids: chosen, layout: { ...layout, outline } },
        'housewright-stickers.pdf',
        'application/pdf',
      );
    } catch (e) {
      toast({ text: errorText(e) });
    } finally {
      busy = false;
    }
  }

  const n = (v: number) => Math.round(v * 10) / 10;
  const perPage = $derived(layout ? layout.columns * layout.rows : 0);
</script>

<section aria-labelledby="labels-h">
  <p><a href="#/home">← Home facts</a></p>
  <h1 id="labels-h">Print stickers</h1>
  <p class="muted small">
    Stick one on each appliance. Scanning it with the phone's camera opens the thing in Housewright
    with its next job and a Done button. The code under it can be typed instead.
  </p>
  {#if error}
    <p role="alert">{error}</p>
  {:else if stickers.length === 0}
    <p class="muted">Add some things first.</p>
  {:else}
    <label for="sheet">Sticker sheet</label>
    <select id="sheet" bind:value={preset} onchange={() => preset === 'custom' && !custom && useCustom()}>
      {#each presets as p (p.key)}<option value={p.key}>{p.label}</option>{/each}
      <option value="custom">My own grid…</option>
    </select>
    {#if preset === 'custom' && custom}
      <fieldset class="card grid-form">
        <legend>Grid, in millimetres</legend>
        {#each [['columns', 'Columns'], ['rows', 'Rows'], ['label_width', 'Label width'], ['label_height', 'Label height'], ['margin_left', 'Left margin'], ['margin_top', 'Top margin'], ['gap_x', 'Gap across'], ['gap_y', 'Gap down'], ['page_width', 'Page width'], ['page_height', 'Page height']] as [k, l] (k)}
          <div>
            <label for={`g-${k}`}>{l}</label>
            <input id={`g-${k}`} type="number" step="0.1" inputmode="decimal" bind:value={custom[k as keyof SheetLayout] as number} />
          </div>
        {/each}
      </fieldset>
    {/if}
    {#if layout}
      <p class="muted small">
        {perPage} per page, labels {n(layout.label_width)} × {n(layout.label_height)} mm. Check with a
        test print on plain paper held against a sheet before using label paper; printers differ.
      </p>
    {/if}
    <label class="check"><input type="checkbox" bind:checked={outline} /> Draw outlines (for a test print)</label>

    <h2>Things ({chosen.length} of {stickers.length})</h2>
    <p class="row">
      <button class="quiet" onclick={() => (chosen = stickers.map((s) => s.item_id))}>All</button>
      <button class="quiet" onclick={() => (chosen = [])}>None</button>
    </p>
    <ul class="preview" data-testid="sticker-preview">
      {#each stickers as s (s.item_id)}
        <li class:off={!chosen.includes(s.item_id)}>
          <label class="sticker">
            <input type="checkbox" checked={chosen.includes(s.item_id)} onchange={() => toggle(s.item_id)} />
            <!-- Generated by the core from our own data; contains no markup from people. -->
            <span class="qr" aria-hidden="true">{@html s.qr_svg}</span>
            <span class="text">
              <strong>{s.code}</strong>
              <span class="small">{s.name}</span>
              {#if s.room_name}<span class="small muted">{s.room_name}</span>{/if}
            </span>
          </label>
        </li>
      {/each}
    </ul>
    <p class="actions">
      <button class="primary" onclick={make} disabled={busy || chosen.length === 0 || !layout}>
        {busy ? 'Making the sheet…' : 'Make the sticker sheet (PDF)'}
      </button>
    </p>
  {/if}
</section>

